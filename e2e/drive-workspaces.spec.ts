import {test,expect} from '@playwright/test';
import {signIn} from './helpers';

test('Workspaces shows organization defaults, creates projects and persists favorites and recents', async ({page,baseURL},info) => {
  await signIn(page,baseURL!);
  const post=async(path:string,data:object)=>{
    const response=await page.request.post(path,{headers:{Origin:baseURL!},data});
    expect(response.ok(),await response.text()).toBe(true);return response.json();
  };
  await post('/api/admin/apps',{id:'drive',enabled:true});
  const org=await post('/api/drive/organization_create',{name:'Workspace Lab'});
  await post('/api/drive/workspace_create',{organization:org.id,name:'Train team'});
  await page.goto('/drive/');
  await page.getByRole('button',{name:'Workspaces',exact:true}).click();
  const directory=page.getByRole('region',{name:'Organization workspaces'});
  await expect(directory.getByRole('article',{name:'Workspace Lab',exact:true})).toContainText('Organization workspace');
  await expect(directory.getByRole('button',{name:'Create workspace',exact:true})).toHaveCount(0);
  await directory.getByRole('button',{name:'Open workspace Train team',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Train team',exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Create or upload',exact:true}).click();
  await page.getByRole('menuitem',{name:'Text document',exact:true}).click();
  const file=page.getByRole('dialog',{name:'New text document',exact:true});
  await file.getByRole('textbox',{name:'Name',exact:true}).fill('Workspace notes.txt');
  await file.getByRole('button',{name:'Create',exact:true}).click();
  await expect(page.getByRole('button',{name:'Actions for Workspace notes.txt'})).toBeVisible();
  await page.getByRole('button',{name:'Workspaces',exact:true}).click();
  await expect(directory.getByRole('article',{name:'Train team',exact:true})).toBeVisible();
  await directory.getByRole('button',{name:'Favorite workspace Train team',exact:true}).click();
  await expect(directory.getByRole('button',{name:'Unfavorite workspace Train team',exact:true})).toHaveAttribute('aria-pressed','true');
  await directory.getByRole('radio',{name:'Favorites',exact:true}).click();
  await expect(directory.getByRole('article')).toHaveCount(1);
  await directory.getByRole('radio',{name:'Recent',exact:true}).click();
  await expect(directory.getByRole('article',{name:'Train team',exact:true})).toBeVisible();
  await directory.getByRole('radio',{name:'All',exact:true}).click();
  await directory.getByRole('textbox',{name:'Filter workspaces by name'}).fill('nothing');
  await expect(directory.getByRole('heading',{name:'No matching workspaces'})).toBeVisible();
  await directory.getByRole('textbox',{name:'Filter workspaces by name'}).fill('');
  await expect(directory.getByRole('button',{name:'Manage members of Workspace Lab'})).toHaveCount(0);
  await page.screenshot({path:info.outputPath('drive-workspaces.png'),animations:'disabled'});
  await page.reload();
  await page.getByRole('button',{name:'Workspaces',exact:true}).click();
  await expect(directory.getByRole('button',{name:'Unfavorite workspace Train team'})).toBeVisible();
  await directory.getByRole('radio',{name:'Recent',exact:true}).click();
  await expect(directory.getByRole('article',{name:'Train team',exact:true})).toBeVisible();
  await page.setViewportSize({width:600,height:850});
  await page.getByRole('button',{name:'Settings',exact:true}).click();
  await page.getByRole('menuitemradio',{name:'Dark',exact:true}).click();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await expect(page.locator('[data-icon-missing]')).toHaveCount(0);
  await page.screenshot({path:info.outputPath('drive-workspaces-narrow.png'),animations:'disabled'});
  await directory.getByRole('button',{name:'Open workspace Train team'}).click();
  await expect(page.getByRole('button',{name:'Actions for Workspace notes.txt'})).toBeVisible();
  await page.getByRole('button',{name:'Workspaces',exact:true}).click();
  await page.getByRole('button',{name:'Create or upload',exact:true}).click();
  const chooserPromise=page.waitForEvent('filechooser');
  await page.getByRole('menuitem',{name:'Upload files',exact:true}).click();
  await (await chooserPromise).setFiles({name:'Directory upload.txt',mimeType:'text/plain',buffer:Buffer.from('directory upload')});
  await expect(page.getByRole('heading',{name:'My files',exact:true})).toBeVisible();
  await expect(page.getByRole('button',{name:'Actions for Directory upload.txt'})).toBeVisible();
});
