  await switchWorkspace(page, 'Visualization'); await openBottomDock(page,'Timeline');
  await page.getByRole('tab',{name:'Surface 1',exact:true}).click();
  const timeline = page.getByRole('region',{name:'Surface 1 timeline',exact:true});
  const mode = timeline.getByRole('combobox',{name:'Timeline mode'});
  await expect(mode).toHaveValue('standard');
  await mode.selectOption('advanced');
  await expect(timeline.locator('.map-lane')).toHaveCount(2);
  await expect(timeline.getByRole('button',{name:'V1',exact:true})).toBeVisible();
  await expect(timeline.locator('.map-track-head').getByRole('button',{name:'A1',exact:true})).toBeVisible();
  const pool = page.getByRole('region',{name:'Media Pool',exact:true});
  await pool.getByRole('button',{name:'Red source',exact:true}).dragTo(timeline.getByLabel('V1 clips'),{targetPosition:{x:4,y:15}});
  await expect(timeline.locator('.map-clip')).toHaveCount(1);
  await timeline.getByRole('button',{name:'Add video track'}).click();
  const clip = timeline.locator('.map-clip').first();
  const from = (await clip.boundingBox())!, to = (await timeline.getByLabel('V2 clips').boundingBox())!;
  await page.mouse.move(from.x+20,from.y+15); await page.mouse.down();
  await page.mouse.move(to.x+140,to.y+15,{steps:12}); await page.mouse.up();
  await expect(timeline.getByLabel('V2 clips').locator('.map-clip')).toHaveCount(1);
  await expect(timeline.getByLabel('V1 clips').locator('.map-clip')).toHaveCount(0);
  await clip.click({button:'right'}); await page.getByRole('menuitem',{name:'Duplicate after clip'}).click();
  await expect(timeline.getByLabel('V2 clips').locator('.map-clip')).toHaveCount(2);
  await clip.click({button:'right'}); await page.getByRole('menuitem',{name:'Move to start'}).click();
  await timeline.locator('.map-ruler').click({position:{x:100,y:10}});
  await clip.click({button:'right'}); await page.getByRole('menuitem',{name:'Split at playhead'}).click();
  await expect(timeline.locator('.map-clip')).toHaveCount(3);
  await clip.click({button:'right'}); await page.getByRole('menuitem',{name:'Lock clip',exact:true}).click();
  await clip.click({button:'right'}); await expect(page.getByRole('menuitem',{name:'Delete clip'})).toBeDisabled(); await page.keyboard.press('Escape');
  await clip.click({button:'right'}); await page.getByRole('menuitem',{name:'Unlock clip'}).click();
  // Actual imported soundtrack, not an empty decorative A1 row.
  await page.locator('input[type=file][accept="image/*,video/*,audio/*"]').setInputFiles({name:'Tone.wav',mimeType:'audio/wav',buffer:wave()});
  const tone = pool.getByRole('button',{name:'Tone.wav',exact:true}); await expect(tone).toBeVisible();
  await tone.dragTo(timeline.getByLabel('A1 clips'),{targetPosition:{x:2,y:15}});
  await expect(timeline.getByLabel('A1 clips').locator('.map-clip')).toHaveCount(1);
  await timeline.locator('.map-ruler').click({position:{x:5,y:10}});
  await timeline.getByRole('button',{name:'Play',exact:true}).click();
  const audio = page.locator('audio[data-timeline-audio]');
  await expect(audio).toHaveCount(1);
  await expect.poll(() => audio.evaluate((n: HTMLAudioElement) => n.currentTime)).toBeGreaterThan(0);
  await expect.poll(() => audio.evaluate((n: HTMLAudioElement) => n.paused)).toBe(false);
  const output = await openOutput(page); await expect(output.locator('audio[data-timeline-audio]')).toHaveCount(0);
  await timeline.getByRole('button',{name:'Pause',exact:true}).click();
  await timeline.getByRole('button',{name:'Mute A1',exact:true}).click(); await expect(audio).toHaveCount(0);
  await timeline.getByRole('button',{name:'Unmute A1',exact:true}).click(); await expect(audio).toHaveCount(1);
  await timeline.locator('.map-track-head').getByRole('button',{name:'A1',exact:true}).click();
