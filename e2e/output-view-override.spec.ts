import { expect, test } from '@playwright/test';
import { emptyShow, newSurface } from '../src/document';
import { newShader } from '../src/features/shader-catalog';
import { openPanel, signIn, switchWorkspace } from './helpers';

test('output Properties follows the workspace and overrides each live output independently', async ({ page, baseURL }, info) => {
  await signIn(page, baseURL!);
  const show = emptyShow(), surface = newSurface(show.output, 0);
  surface.source.shader = newShader('tunnel');
  show.scenes[0].surfaces = [surface];
  show.outputs.push({ ...show.outputs[0], id: 'other-output', name: 'Output 2' });
  const response = await page.request.post('/api/library/create', { headers: { Origin: baseURL! }, data: {
    app: 'map', scope: 'personal', name: 'Output views.aethermap', data_base64: Buffer.from(JSON.stringify(show)).toString('base64'),
  } });
  expect(response.ok()).toBe(true);
  await page.goto(`/map/index.html?document=${(await response.json()).id}`);
  await openPanel(page, 'Outputs');
  const rows = page.getByRole('tree', { name: 'Outputs', exact: true }).getByRole('treeitem');
  await rows.first().click();
  const popup1 = page.waitForEvent('popup'); await rows.first().dblclick(); const first = await popup1;
  const popup2 = page.waitForEvent('popup'); await rows.nth(1).dblclick(); const second = await popup2;
  const inspector = page.getByRole('region', { name: 'Selection properties' });
  const view = inspector.getByRole('combobox', { name: 'Output view', exact: true });
  const pattern = inspector.getByRole('combobox', { name: 'Output mapping pattern' });
  await rows.first().click();
  await expect(view).toHaveValue('workspace');
  await expect(pattern).toBeVisible();
  await expect(first.locator('.map-surface-grid')).toHaveCount(1);
  await switchWorkspace(page, 'Visualization');
  await expect(pattern).toHaveCount(0);
  await expect(inspector.getByRole('combobox', { name: 'Recording size' })).toBeVisible();
  await expect(first.locator('.map-surface canvas')).toHaveCount(1);
  await view.selectOption('mapping');
  await expect(pattern).toBeVisible();
  await pattern.selectOption('grid');
  const sections = inspector.getByRole('textbox', { name: 'Output pattern sections' });
  await sections.fill('9'); await sections.press('Tab');
  await expect(first.locator('.map-surface-grid line')).toHaveCount(16);
  await expect(second.locator('.map-surface canvas')).toHaveCount(1);
  await page.screenshot({ path: info.outputPath('output-mapping-override.png'), animations: 'disabled' });
  await switchWorkspace(page, 'Mapping');
  await view.selectOption('visualization');
  await expect(first.locator('.map-surface canvas')).toHaveCount(1);
  await expect(second.locator('.map-surface-grid')).toHaveCount(1);
  await expect(pattern).toHaveCount(0);
  await expect(page.locator('.map-save-state')).toHaveText('Saved');
  await page.reload(); await rows.first().click();
  await expect(view).toHaveValue('visualization');
  await expect(first.locator('.map-surface canvas')).toHaveCount(1);
  await view.selectOption('workspace');
  await expect(pattern).toBeVisible();
  await expect(sections).toHaveValue('9');
  await expect(first.locator('.map-surface-grid line')).toHaveCount(16);
  await inspector.getByRole('button', { name: 'Use show mapping design' }).click();
  await expect(pattern).toHaveValue('checker');
  await expect(first.locator('.map-surface-grid line')).toHaveCount(0);
  await switchWorkspace(page, 'Visualization');
  await expect(first.locator('.map-surface canvas')).toHaveCount(1);
  await expect(second.locator('.map-surface canvas')).toHaveCount(1);
  await first.close(); await second.close();
});
