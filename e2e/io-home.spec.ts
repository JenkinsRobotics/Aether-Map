import { expect, test } from "@playwright/test";
import { createIOProject, signIn } from "./helpers";

test("IO shares library chrome, app discovery and document controls", async ({ page, baseURL }, info) => {
  await signIn(page, baseURL!);
  await page.request.post("/api/admin/apps", { headers: { Origin: baseURL! }, data: { id: "io", enabled: true } });
  await page.goto("/");
  const card = page.getByRole("link", { name: /^Aether IO .*Open application/ });
  await expect(card).toBeVisible();
  await expect(card.locator(".application-art > img")).toBeVisible();
  await page.goto("/cad/");
  const cadHeader = page.locator(".aui-application-home-header");
  await expect(cadHeader).toBeVisible();
  const height = (await cadHeader.boundingBox())!.height;
  await page.goto("/io/");
  const header = page.locator(".aui-application-home-header");
  await expect(header).toBeVisible();
  expect((await header.boundingBox())!.height).toBe(height);
  await header.getByRole("button", { name: "Aether Studio applications", exact: true }).click();
  await expect(page.getByRole("menuitem", { name: /^Aether IO Electronics/ })).toBeVisible();
  await page.keyboard.press("Escape");
  await expect(page.getByRole("heading", { name: "Get started" })).toBeVisible();
  await page.screenshot({ path: info.outputPath("io-home.png") });
  await createIOProject(page);
  await expect(page.locator(".io-document-bar")).toBeVisible();
  await page.getByRole("button", { name: "Document controls", exact: true }).click();
  await expect(page.getByRole("menuitem", { name: "Download project", exact: true })).toBeVisible();
  await page.getByRole("menuitem", { name: "Project library", exact: true }).click();
  await page.getByRole("button", { name: "My files", exact: true }).click();
  await expect(page.getByRole("heading", { name: "My files", exact: true })).toBeVisible();
  const search = page.getByRole("textbox", { name: "Search Aether IO files" });
  await search.fill("no-match");
  await expect(page.getByText("No matching projects. Try another search.")).toBeVisible();
  await search.fill("ESP32");
  await expect(page.getByRole("button", { name: /ESP32 status indicator\.aetherio/ }).first().locator('[data-icon="file-circuit"]')).toHaveCount(1);
  await page.getByRole("button", { name: /ESP32 status indicator\.aetherio/ }).first().dblclick();
  await expect(page.locator(".io-part")).toHaveCount(6);
  await page.screenshot({ path: info.outputPath("io-editor.png"), animations: "disabled" });
  await page.evaluate(() => document.dispatchEvent(new Event("aether-open-settings", { cancelable: true })));
  await expect(page.getByRole("dialog", { name: "Aether IO settings" })).toBeVisible();
  await page.getByRole("dialog", { name: "Aether IO settings" }).getByRole("button", { name: /Close/ }).click();
  await page.getByRole("link", { name: "Aether IO home", exact: true }).click();
  await page.setViewportSize({ width: 800, height: 900 });
  await page.getByRole("button", { name: "Collapse IO home navigation" }).click();
  await expect(page.locator(".io-home-nav")).toHaveClass(/aui-sidebar--collapsed/);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: info.outputPath("io-home-narrow.png"), animations: "disabled" });
});
