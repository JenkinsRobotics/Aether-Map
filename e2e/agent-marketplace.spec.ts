import { expect, test } from '@playwright/test';
import { signIn } from './helpers';

test('Studio marketplace installs account plugins, persists enablement, and starts cancellable OAuth', async ({ page, baseURL }, info) => {
  await signIn(page, baseURL!);
  await page.goto('/?workspace=admin&section=plugins');
  await expect(page.getByRole('heading', { name: 'Plugin marketplace' })).toBeVisible();
  const chatgpt = page.getByRole('article', { name: 'ChatGPT plugin' });
  await expect(page.getByRole('article')).toHaveCount(3);
  await chatgpt.getByRole('button', { name: 'Install', exact: true }).click();
  await expect(chatgpt.getByRole('button', { name: 'Disable', exact: true })).toBeEnabled();
  await chatgpt.getByRole('button', { name: 'Disable', exact: true }).click();
  await page.reload();
  await chatgpt.getByRole('button', { name: 'Enable', exact: true }).click();
  await expect(chatgpt.getByRole('button', { name: 'Disable', exact: true })).toBeVisible();
  await page.goto('/?plugins');
  await expect(chatgpt.getByRole('button', { name: 'Install', exact: true })).toHaveCount(0);
  await chatgpt.getByRole('button', { name: 'Sign in with ChatGPT' }).click();
  const link = chatgpt.getByRole('link', { name: 'Continue to ChatGPT' });
  await expect(link).toBeVisible();
  const url = new URL((await link.getAttribute('href'))!);
  expect(url.origin).toBe('https://auth.openai.com');
  expect(url.searchParams.get('client_id')).toBe('dynamic_agent_client');
  expect(url.searchParams.get('code_challenge_method')).toBe('S256');
  expect(url.searchParams.get('scope')).toContain('chatgpt.tokens.use.direct');
  await chatgpt.getByRole('button', { name: 'Cancel', exact: true }).click();
  await expect(chatgpt.getByRole('button', { name: 'Sign in with ChatGPT' })).toBeEnabled();
  await page.screenshot({ path: info.outputPath('marketplace.png'), fullPage: true });
  await page.getByRole('textbox', { name: 'Search plugins' }).fill('Google');
  await expect(page.getByRole('article')).toHaveCount(1);
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.goto('/?agent=map');
  await expect(page.getByRole('textbox')).toHaveCount(1);
  await expect(page.getByRole('button', { name: 'Connect agent' })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Send' })).toBeDisabled();
  await page.setViewportSize({ width: 1440, height: 980 });
  await page.goto('/map/index.html?new=show');
  await page.getByLabel('Account: End to End').click();
  await page.locator('.suite-account-menu').getByRole('button', { name: 'Aether Agent', exact: true }).click();
  await expect(page.getByRole('region', { name: 'Projection assistant' })).toBeVisible();
  await expect(page.getByRole('textbox', { name: 'Ask Aether Agent' })).toHaveCount(1);
  await expect(page.locator('.suite-agent-drawer')).toHaveCount(0);
});
