import {test,expect} from '@playwright/test';
import {signIn} from './helpers';

test('Recycle bin shows deletion metadata and confirms a complete immutable empty selection', async ({page,baseURL},info) => {
  await signIn(page,baseURL!);
  const post=async(path:string,data:object)=>{
    const response=await page.request.post(path,{headers:{Origin:baseURL!},data});
    expect(response.ok(),await response.text()).toBe(true); return response.json();
  };
  await post('/api/admin/apps',{id:'drive',enabled:true});
  const create=(name:string,kind='file',parent?:string)=>post('/api/drive/create',{name,kind,parent,data_base64:Buffer.from('recover me').toString('base64')});
  const folder=await create('Recycle documents','folder');
  const note=await create('Recycle note.txt','file',folder.id);
  const other=await create('Recycle other.pdf');
  for(const id of [note.id,other.id]) await post('/api/drive/trash',{id});
  await page.goto('/drive/');
  await page.getByRole('button',{name:'Recycle bin',exact:true}).click();
  const table=page.getByRole('table',{name:'Drive files'});
  for(const name of ['Name','Deleted','Deleted by','Created by','File size']) await expect(table.getByRole('columnheader',{name,exact:true})).toBeVisible();
  await expect(table.getByRole('columnheader',{name:'Deleted',exact:true})).toHaveAttribute('aria-sort','descending');
  const noteRow=table.getByRole('row').filter({hasText:'Recycle note.txt'});
  await expect(noteRow).toContainText('My files > Recycle documents');
  await expect(noteRow).toContainText('End to End');
  await expect(noteRow.locator('[data-icon="file-text"]')).toHaveCount(1);
  await expect(page.getByRole('button',{name:'More file types',exact:true})).toBeHidden();
  await page.screenshot({path:info.outputPath('drive-recycle.png'),animations:'disabled'});
  await page.getByRole('button',{name:'Restore Recycle note.txt',exact:true}).click();
  await expect(noteRow).toHaveCount(0);
  const restored=await post('/api/drive/read',{id:note.id});
  expect(restored.parent).toBe(folder.id);
  expect(Buffer.from(restored.data_base64,'base64').toString()).toBe('recover me');
  await post('/api/drive/trash',{id:folder.id});
  await page.getByRole('button',{name:'Refresh files'}).click();
  await page.getByRole('button',{name:'Restore Recycle documents',exact:true}).click();
  expect((await post('/api/drive/read',{id:note.id})).parent).toBe(folder.id);
  await post('/api/drive/trash',{id:note.id});
  await page.getByRole('textbox',{name:'Search Drive'}).fill('Recycle other');
  await expect(table.locator('tbody tr')).toHaveCount(1);
  await page.getByRole('button',{name:'Empty recycle bin',exact:true}).click();
  const dialog=page.getByRole('dialog',{name:'Empty recycle bin?',exact:true});
  await expect(dialog).toContainText('Recycle note.txt');
  await expect(dialog).toContainText('Recycle other.pdf');
  await dialog.getByRole('button',{name:'Cancel',exact:true}).click();
  await expect(table.locator('tbody tr')).toHaveCount(1);
  await page.getByRole('button',{name:'Empty recycle bin',exact:true}).click();
  await expect(dialog).toBeVisible();
  // A newly deleted file was never approved by this confirmation.
  const fresh=await create('Recycle fresh.txt');
  await post('/api/drive/trash',{id:fresh.id});
  await dialog.getByRole('button',{name:'Empty recycle bin',exact:true}).click();
  await expect(dialog).toBeHidden();
  const remaining=await post('/api/drive/list',{view:'trash'});
  expect(remaining.files.map((f:any)=>f.id)).toContain(fresh.id);
  expect(remaining.files.map((f:any)=>f.id)).not.toContain(note.id);
  expect(remaining.files.map((f:any)=>f.id)).not.toContain(other.id);
  await page.getByRole('textbox',{name:'Search Drive'}).fill('Recycle fresh');
  await expect(table.locator('tbody tr')).toHaveCount(1);
  await page.getByRole('button',{name:'Settings',exact:true}).click();
  await page.getByRole('menuitemradio',{name:'Dark',exact:true}).click();
  await page.setViewportSize({width:600,height:850});
  await expect(table.getByRole('button',{name:'Restore Recycle fresh.txt'})).toBeVisible();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await expect(page.locator('[data-icon-missing]')).toHaveCount(0);
  await page.screenshot({path:info.outputPath('drive-recycle-narrow.png'),animations:'disabled'});
});
