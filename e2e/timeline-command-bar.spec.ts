import { test, expect } from '@playwright/test';
import { signIn, switchWorkspace, clickRibbon, openAppSettings } from './helpers';

test('compact command row, timeline tabs, mixer toggle, snapping, trimming and zoom are functional', async ({page,baseURL},info) => {
  await page.setViewportSize({width:1968,height:1100});
  await signIn(page,baseURL!); await page.goto('/map/index.html?new=show');
  await switchWorkspace(page,'Visualization'); await clickRibbon(page,'Text');
  const tools=page.getByRole('toolbar',{name:'Timeline tools'}), timeline=page.getByRole('region',{name:'Main timeline',exact:true});
  const bottom=page.getByRole('toolbar',{name:'Map workspace dock tabs'});
  await expect(bottom.getByRole('button')).toHaveCount(2);
  await page.getByRole('combobox',{name:'Timeline mode'}).selectOption('advanced');
  const tablist=page.getByRole('tablist',{name:'Timelines',exact:true});
  await expect(tablist.getByRole('tab',{name:'Main'})).toHaveAttribute('aria-selected','true');
  const bounds=await tools.boundingBox(), tabs=await tablist.boundingBox(), mixer=await page.getByRole('complementary',{name:'Audio mixer'}).boundingBox();
  expect(bounds!.y+bounds!.height).toBeLessThanOrEqual(tabs!.y+1);
  expect(bounds!.x+bounds!.width).toBeGreaterThanOrEqual(mixer!.x+mixer!.width-1);
  await tools.getByRole('button',{name:'Audio mixer',exact:true}).click();
  await expect(page.getByRole('complementary',{name:'Audio mixer'})).toHaveCount(0);
  await expect(timeline).toBeVisible(); await tools.getByRole('button',{name:'Audio mixer',exact:true}).click();
  await tools.getByRole('button',{name:'Snapping options'}).click();
  const snap=page.getByRole('dialog',{name:'Snapping options'});
  await snap.getByRole('checkbox',{name:'Playhead',exact:true}).uncheck();
  await snap.getByRole('checkbox',{name:'Time grid (0.1 s)',exact:true}).uncheck();
  await page.keyboard.press('Escape');
  await tools.getByRole('button',{name:'Snapping options'}).click(); await expect(snap.getByRole('checkbox',{name:'Playhead',exact:true})).not.toBeChecked(); await page.keyboard.press('Escape');
  const clip=timeline.locator('.map-clip').first(), original=(await clip.boundingBox())!;
  await clip.click(); const ruler=timeline.locator('.map-ruler'), rulerBox=(await ruler.boundingBox())!;
  await ruler.click({position:{x:rulerBox.width*.2,y:8}});
  await tools.getByRole('button',{name:'Trim start to playhead',exact:true}).click();
  await expect.poll(async()=> (await clip.boundingBox())!.width).toBeLessThan(original.width-10);
  await page.keyboard.press('ControlOrMeta+z');
  await expect.poll(async()=> (await clip.boundingBox())!.width).toBeCloseTo(original.width,0);
  await tools.getByRole('button',{name:'Trim clips',exact:true}).click();
  const box=(await clip.boundingBox())!;
  await page.mouse.move(box.x+box.width-20,box.y+box.height/2); await page.mouse.down(); await page.mouse.move(box.x+box.width-100,box.y+box.height/2,{steps:6}); await page.mouse.up();
  await expect.poll(async()=> (await clip.boundingBox())!.width).toBeLessThan(original.width-40);
  await tools.getByRole('button',{name:'Select clips',exact:true}).click();
  await tools.getByRole('slider',{name:'Timeline zoom'}).fill('2');
  await expect.poll(async()=> (await ruler.boundingBox())!.width).toBeGreaterThan(rulerBox.width*1.8);
  await tools.getByRole('button',{name:'Fit',exact:true}).click();
  await page.locator('.map-sequence-tabs-row').getByRole('button',{name:'New timeline',exact:true}).click();
  const dialog=page.getByRole('dialog',{name:'New timeline',exact:true}); await dialog.getByRole('textbox',{name:'Timeline name'}).fill('Wall sequence'); await dialog.getByRole('button',{name:'Create',exact:true}).click();
  await expect(tablist.getByRole('tab',{name:'Wall sequence',exact:true})).toHaveAttribute('aria-selected','true');
  await page.getByRole('combobox',{name:'Timeline mode'}).selectOption('standard');
  await expect(tablist.getByRole('tab',{name:'Main',exact:true})).toHaveAttribute('aria-selected','true');
  await expect(tablist.getByRole('tab',{name:'Wall sequence',exact:true})).toHaveCount(0);
  await expect(page.getByRole('button',{name:'Timeline: Wall sequence',exact:true})).toHaveCount(0);
  await page.getByRole('combobox',{name:'Timeline mode'}).selectOption('advanced');
  await expect(tablist.getByRole('tab',{name:'Wall sequence',exact:true})).toBeVisible();

  await tablist.getByRole('tab',{name:'Main',exact:true}).click(); await expect(clip).toBeVisible();
  await expect(tools.locator('[data-icon-missing]')).toHaveCount(0);
  await page.screenshot({path:info.outputPath('timeline-light.png'),animations:'disabled'});
  await openAppSettings(page); const settings=page.getByRole('dialog',{name:'Aether Map settings'});
  await settings.getByRole('button',{name:'Appearance & icons',exact:true}).click();
  await settings.getByRole('combobox',{name:'Interface theme'}).selectOption('aether-studio'); await settings.getByRole('combobox',{name:'Color mode'}).selectOption('dark'); await settings.getByRole('button',{name:/Close/}).click();
  await page.screenshot({path:info.outputPath('timeline-dark.png'),animations:'disabled'});
  await page.setViewportSize({width:1000,height:800});
  await expect(tools.getByRole('slider',{name:'Master output volume'})).toBeInViewport();
  await expect(tools.getByRole('button',{name:'Audio mixer',exact:true})).toBeInViewport();
});
