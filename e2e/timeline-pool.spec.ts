import { expect, test } from '@playwright/test';
import { emptyShow, newSurface } from '../src/document';
import { addPoolAsset, normalizeMediaPool } from '../src/media-pool';
import { signIn, switchWorkspace, openBottomDock, openAppSettings } from './helpers';

test('Media Pool creates real timelines, opens tabs and schedules nested uses without copying media', async ({ page, baseURL }, info) => {
  await signIn(page, baseURL!);
  let show = normalizeMediaPool(emptyShow());
  show.scenes[0].surfaces = [newSurface(show.output, 0), newSurface(show.output, 1)];
  show = addPoolAsset(show, { mediaId:null, rect:[0,0,1920,1080], fill:'#ff0000' }, 'Red source');
  const created = await page.request.post('/api/library/create', { headers:{Origin:baseURL!}, data:{app:'map',scope:'personal',name:'Nested timelines.aethermap',data_base64:Buffer.from(JSON.stringify(show)).toString('base64')} });
  expect(created.ok()).toBe(true);
  await page.goto(`/map/index.html?document=${(await created.json()).id}`);
  await switchWorkspace(page,'Visualization'); await openBottomDock(page,'Timeline');
  const main = page.getByRole('region',{name:'Main timeline',exact:true});
  const pool = page.getByRole('region',{name:'Media Pool',exact:true});
  await expect(pool.getByRole('button',{name:'Timeline: Main',exact:true})).toBeVisible();
  await main.getByRole('combobox',{name:'Timeline mode'}).selectOption('advanced');
  await pool.getByRole('button',{name:'Timelines',exact:true}).click();
  await pool.getByRole('button',{name:'New timeline',exact:true}).click();
  const dialog = page.getByRole('dialog',{name:'New timeline',exact:true});
  await dialog.getByRole('textbox',{name:'Timeline name'}).fill('Box sequence');
  await dialog.getByRole('button',{name:'Create',exact:true}).click();
  const child = page.getByRole('region',{name:'Box sequence timeline',exact:true});
  await expect(child).toBeVisible(); await expect(child.locator('.map-lane')).toHaveCount(2);
  await expect(child.locator('.map-clip')).toHaveCount(0);
  await pool.getByRole('button',{name:'All media',exact:true}).click();
  await pool.getByRole('button',{name:'Red source',exact:true}).dragTo(child.getByLabel('V1 clips'),{targetPosition:{x:2,y:15}});
  await expect(child.locator('.map-clip')).toHaveCount(1);
  await child.locator('.map-clip').click();
  const assignments = page.getByRole('group',{name:'Asset surface assignments'});
  await assignments.getByRole('button',{name:'Assign to entire Scene 1'}).click();
  await page.getByRole('button',{name:'Assign to all surfaces',exact:true}).click();
  await page.getByRole('combobox',{name:'Surface assignment mapping'}).selectOption('span');
  await page.getByRole('tab',{name:'Main',exact:true}).click();
  await expect(main.locator('.map-clip')).toHaveCount(2);
  await main.getByRole('button',{name:'Add video track',exact:true}).click();
  await pool.getByRole('button',{name:'Timeline: Box sequence',exact:true}).dragTo(main.getByLabel('V3 clips'),{targetPosition:{x:2,y:15}});
  await expect(main.locator('.map-clip')).toHaveCount(3);
  await main.getByLabel('V3 clips').locator('.map-clip').click();
  await expect(page.getByRole('region',{name:'Timeline clip properties'})).toBeVisible();
  // Child starts at the drop time; scrub into it and inspect actual rendering.
  await main.locator('.map-ruler').click({position:{x:50,y:10}});
  await expect(page.locator('.map-output-preview .map-fill')).toHaveCount(1);
  await pool.getByRole('button',{name:'Timeline: Box sequence',exact:true}).click({button:'right'});
  await expect(page.getByRole('menuitem',{name:'Delete timeline',exact:true})).toBeDisabled();
  await page.getByRole('menuitem',{name:'Rename timeline',exact:true}).click();
  const rename = page.getByRole('dialog',{name:'Rename timeline',exact:true});
  await rename.getByRole('textbox',{name:'Timeline name'}).fill('Box lights');
  await rename.getByRole('button',{name:'Save',exact:true}).click();
  await pool.getByRole('button',{name:'Timeline: Box lights',exact:true}).dblclick();
  const renamed = page.getByRole('region',{name:'Box lights timeline',exact:true});
  await expect(renamed.locator('.map-clip')).toHaveCount(1);
  await pool.getByRole('button',{name:'Timeline: Box lights',exact:true}).click({button:'right'});
  await expect(page.getByRole('menuitem',{name:'Append timeline to current track'})).toBeDisabled();
  await page.keyboard.press('Escape');
  await page.screenshot({path:info.outputPath('timeline-pool.png')});
  await openAppSettings(page);
  const settings = page.getByRole('dialog',{name:'Aether Map settings'});
  await settings.getByRole('button',{name:'Appearance & icons',exact:true}).click();
  await settings.getByRole('combobox',{name:'Interface theme'}).selectOption('aether-studio');
  await settings.getByRole('combobox',{name:'Color mode'}).selectOption('dark');
  await settings.getByRole('button',{name:/Close/}).click();
  await page.screenshot({path:info.outputPath('timeline-pool-dark.png')});
  await expect(page.getByText('Saved',{exact:true}).first()).toBeVisible();
  await page.reload(); await switchWorkspace(page,'Visualization'); await openBottomDock(page,'Timeline');
  await expect(page.getByRole('tab',{name:'Box lights',exact:true})).toBeVisible();
  await expect(renamed.locator('.map-clip')).toHaveCount(1);
  await page.getByRole('tab',{name:'Main',exact:true}).click();
  await expect(main.locator('.map-clip')).toHaveCount(3);
  await expect(pool.getByRole('button',{name:'Red source',exact:true})).toHaveCount(1);
});
