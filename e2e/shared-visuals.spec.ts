import { normalizeVisuals } from '../src/visual-document';
import { expect, test, type Page } from '@playwright/test';
import { emptyShow, newSurface } from '../src/document';
import { contentClip } from '../src/surface-assets';
import { signIn, switchWorkspace, openPanel, openOutput, openBottomDock } from './helpers';
const row = (page: Page, tree: string, name: string) => page.getByRole('tree', { name: tree, exact: true }).getByRole('treeitem').filter({ has: page.locator('.aui-tree-label', { hasText: new RegExp(`^${name}$`) }) });

test('legacy visual migrates to Assets; shared Repeat/Span targets, scene layering, timeline, effects and reload', async ({ page, baseURL }, info) => {
  await signIn(page, baseURL!);
  const show = emptyShow(); const a = newSurface(show.output, 0), b = newSurface(show.output, 1);
  a.name = 'Left face'; b.name = 'Right face';
  a.corners = [[100,100],[500,100],[500,500],[100,500]];
  b.corners = [[500,100],[900,100],[900,500],[500,500]];
  a.source.fill = '#ff0000';
  a.clips = [{ ...contentClip(a.source, [], 0, 'red-visual'), name: 'Red visual', durationS: 90 }]; a.sequence = true;
  show.scenes[0].surfaces = [a,b];
  const created = await page.request.post('/api/library/create', { headers: { Origin: baseURL! }, data: { app:'map', scope:'personal', name:'Shared visuals.aethermap', data_base64: Buffer.from(JSON.stringify(show)).toString('base64') } });
  expect(created.ok()).toBe(true);
  await page.goto(`/map/index.html?document=${(await created.json()).id}`);
  await switchWorkspace(page, 'Visualization'); await openPanel(page,'Layers');
  await expect(row(page,'Layers','Red visual')).toHaveCount(0);
  await row(page,'Clip index','Red visual').dblclick();
  const props = page.getByRole('region',{name:'Selection properties'});
  await expect(props.getByRole('textbox',{name:'Asset name'})).toHaveValue('Red visual');
  await expect(page.locator('.aui-feature-window')).toHaveCount(0);
  await props.getByRole('tab',{name:'Targets',exact:true}).click();
  await expect(props.getByRole('checkbox',{name:'Left face',exact:true})).toBeChecked();
  await props.getByRole('checkbox',{name:'Right face',exact:true}).check();
  await expect(page.locator('.map-output-preview .map-fill')).toHaveCount(2);
  const output = await openOutput(page);
  await expect(output.locator('.map-output .map-fill')).toHaveCount(2);
  const transforms = () => output.locator('.map-output .map-fill').evaluateAll(nodes => nodes.map(n => (n as HTMLElement).style.transform));
  const repeated = await transforms(); expect(repeated[0]).not.toBe(repeated[1]);
  await props.getByRole('combobox',{name:'Visual mapping'}).selectOption('span');
  await expect.poll(async () => { const t = await transforms(); return t.length === 1 && t[0] !== repeated[0]; }).toBe(true);
  await props.getByRole('tab',{name:'Effects',exact:true}).click();
  await props.getByRole('combobox',{name:'Effect type'}).selectOption('grayscale');
  await props.getByRole('button',{name:'Add effect',exact:true}).click();
  await props.getByRole('textbox',{name:'grayscale amount'}).fill('100');
  await props.getByRole('textbox',{name:'grayscale amount'}).press('Enter');
  await expect(output.locator('[style*="grayscale(1)"]')).toHaveCount(1);
  await props.getByRole('tab',{name:'Targets',exact:true}).click();
  await props.getByRole('button',{name:'Duplicate as independent visual'}).click();
  await expect(row(page,'Clip index','Red visual copy')).toBeVisible();
  await props.getByRole('tab',{name:'Targets',exact:true}).click();
  await props.getByRole('button',{name:'Clear targets'}).click();
  await props.getByRole('checkbox',{name:'Scene 1 · Entire scene',exact:true}).check();
  await props.getByRole('button',{name:'Move backward',exact:true}).click();
  await openBottomDock(page,'Timeline');
  await expect(page.locator('.map-clip')).toHaveCount(2);
  await row(page,'Layers','Left face').click();
  await expect(props.getByRole('textbox',{name:'Surface name'})).toHaveValue('Left face');
  await expect(props.getByRole('textbox',{name:'Asset name'})).toHaveCount(0);
  await expect(page.locator('.map-save-state')).toHaveText('Saved');
  await page.reload(); await switchWorkspace(page,'Visualization'); await openPanel(page,'Layers');
  await row(page,'Clip index','Red visual').click();
  await props.getByRole('tab',{name:'Targets',exact:true}).click();
  await expect(props.getByRole('combobox',{name:'Visual mapping'})).toHaveValue('span');
  await expect(props.getByRole('checkbox',{name:'Right face',exact:true})).toBeChecked();
  await page.screenshot({path:info.outputPath('shared-visuals.png')});
  await output.close();
});

test('Span preserves a surface bitmap cutout in physical output coordinates', async ({ page, baseURL }) => {
  await signIn(page, baseURL!);
  const png = await page.evaluate(() => { const c = document.createElement('canvas'); c.width = 100; c.height = 100; const ctx = c.getContext('2d')!; ctx.fillStyle = 'white'; ctx.fillRect(0,0,50,100); return c.toDataURL(); });
  const show = emptyShow(); show.scenes[0].artboard = { widthPx: 200, heightPx: 100 };
  const a = newSurface(show.output, 0), b = newSurface(show.output, 1);
  a.corners = [[0,0],[100,0],[100,100],[0,100]]; b.corners = [[100,0],[200,0],[200,100],[100,100]];
  a.source = { mediaId:null, rect:[0,0,100,100], fill:'#ff0000' }; a.alphaMask = { png }; show.scenes[0].surfaces = [a,b];
  const shared = normalizeVisuals(show); shared.visuals![0].targets.push({ sceneID:show.activeSceneId, surfaceID:b.id }); shared.visuals![0].mapping = 'span';
  const created = await page.request.post('/api/library/create', { headers:{ Origin:baseURL! }, data:{ app:'map',scope:'personal',name:'Span cutout.aethermap',data_base64:Buffer.from(JSON.stringify(shared)).toString('base64') } });
  await page.goto(`/map/index.html?document=${(await created.json()).id}`); await switchWorkspace(page,'Visualization');
  const output = await openOutput(page);
  await expect(output.locator('.map-output .map-fill')).toHaveCount(2);
  await expect.poll(async () => {
    const image = (await output.locator('.map-output').screenshot()).toString('base64');
    return output.evaluate(async encoded => {
      const image = new Image(); image.src = 'data:image/png;base64,' + encoded; await image.decode();
      const c = document.createElement('canvas'); c.width=image.width; c.height=image.height; const ctx=c.getContext('2d')!; ctx.drawImage(image,0,0);
      const outer = document.querySelector('.map-output')!.getBoundingClientRect(), raster = document.querySelector('.map-output-raster')!.getBoundingClientRect();
      return [25,75,125,175].map(x => Array.from(ctx.getImageData(Math.round(raster.left-outer.left+x/200*raster.width), Math.round(raster.top-outer.top+raster.height/2),1,1).data).slice(0,3));
    }, image);
  }).toEqual([[255,0,0],[0,0,0],[255,0,0],[255,0,0]]);
  await output.close();
});
