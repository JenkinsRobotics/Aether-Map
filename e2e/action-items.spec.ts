import {expect,test} from '@playwright/test';
import {openAppSettings,signIn} from './helpers';

test('Action items search, filter, sort, create and edit real tasks and reminders',async({page,baseURL},info)=>{
  await signIn(page,baseURL!);await page.goto('/map/index.html?new=show');
  await page.getByRole('toolbar',{name:'Left sidebar tabs',exact:true}).getByRole('button',{name:'Action items',exact:true}).click();
  const panel=page.getByRole('region',{name:'Action items',exact:true});
  await expect(panel.getByText('No action items found for the current filter.')).toBeVisible();
  await expect(panel.getByLabel('1 assignee filter')).toBeVisible();
  await expect(panel.getByRole('textbox',{name:'Action items text'})).toHaveCount(0);
  await page.screenshot({path:info.outputPath('action-items-empty.png'),animations:'disabled'});
  const bounds=await panel.boundingBox();
  const create=async(type:string,text:string,due:string)=>{
    await panel.getByRole('button',{name:'Create action item'}).click();
    const dialog=page.getByRole('dialog',{name:'Create action item',exact:true});
    await dialog.getByLabel('New action item type').selectOption(type);
    await dialog.getByLabel('Action items text').fill(text);
    await dialog.getByLabel('Due date',{exact:true}).fill(due);
    await dialog.getByRole('button',{name:type==='tasks'?'Add task':'Add reminder',exact:true}).click();
    await expect(dialog).toBeHidden();
  };
  await create('tasks','Approve design','2026-12-01');
  await create('reminders','Call supplier','2000-01-01');
  expect((await panel.boundingBox())?.width).toBe(bounds?.width);
  await panel.getByLabel('Action item type',{exact:true}).selectOption('reminders');
  await expect(panel.getByText('Approve design',{exact:true})).toHaveCount(0);
  await expect(panel.getByText('Call supplier',{exact:true})).toBeVisible();
  await panel.getByRole('button',{name:'Due date filter'}).click();
  await page.getByRole('menuitemradio',{name:'Overdue',exact:true}).click();
  await expect(panel.getByText('Call supplier',{exact:true})).toBeVisible();
  await panel.getByLabel('Status for Call supplier').selectOption('done');
  await expect(panel.getByText('No action items found for the current filter.')).toBeVisible();
  await panel.getByRole('button',{name:'Clear action item filters'}).click();
  await panel.getByLabel('Action item status').selectOption('done');
  await expect(panel.getByText('Call supplier',{exact:true})).toBeVisible();
  await panel.getByRole('button',{name:'Actions for Call supplier'}).click();
  await page.getByRole('menuitem',{name:'Edit item',exact:true}).click();
  const edit=page.getByRole('dialog',{name:'Edit action item'});
  await expect(edit.getByLabel('New action item type')).toHaveValue('reminders');
  await edit.getByLabel('Action items text').fill('Call supplier again');
  await edit.getByRole('button',{name:'Save changes'}).click();
  await expect(edit).toBeHidden();
  await panel.getByRole('button',{name:'Sort action items'}).click();
  await page.getByRole('menuitemradio',{name:'Name',exact:true}).click();
  await expect(panel.getByRole('listitem').first()).toContainText('Approve design');
  await panel.getByRole('searchbox',{name:'Search in Action items'}).fill('supplier');
  await expect(panel.getByRole('listitem')).toHaveCount(1);
  await panel.getByRole('button',{name:'Create action item'}).click();
  const dialog=page.getByRole('dialog',{name:'Create action item'});
  await dialog.getByLabel('Action items text').fill('Discard this');
  await dialog.getByRole('button',{name:'Cancel',exact:true}).click();
  await expect(panel.getByText('Discard this')).toHaveCount(0);
  await page.reload();
  const tab=page.getByRole('toolbar',{name:'Left sidebar tabs',exact:true}).getByRole('button',{name:'Action items',exact:true});
  if(await tab.getAttribute('aria-pressed')!=='true')await tab.click();
  await expect(panel.getByText('Call supplier again',{exact:true})).toBeVisible();
  await expect(panel.getByLabel('Status for Call supplier again')).toHaveValue('done');
  await expect(panel.locator('[data-icon-missing]')).toHaveCount(0);
  await openAppSettings(page);
  const settings=page.getByRole('dialog',{name:'Aether Map settings'});
  await settings.getByRole('button',{name:'Appearance & icons',exact:true}).click();
  await settings.getByRole('combobox',{name:'Interface theme'}).selectOption('aether-studio');
  await settings.getByRole('combobox',{name:'Color mode'}).selectOption('dark');
  await settings.getByRole('button',{name:/Close/}).click();
  await page.screenshot({path:info.outputPath('action-items-populated-dark.png'),animations:'disabled'});
});
