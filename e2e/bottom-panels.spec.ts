import { expect, test } from '@playwright/test';
import { signIn, switchWorkspace, clickRibbon, openAppSettings } from './helpers';

test('timeline owns mixer visibility and preserves its preference, resize and settings in both modes', async ({ page, baseURL }, info) => {
  await signIn(page, baseURL!);
  await page.goto('/map/index.html?new=show');
  await page.getByRole('region',{name:'Map tools'}).getByRole('button',{name:'Cube',exact:true}).click();
  await switchWorkspace(page,'Visualization');
  await clickRibbon(page,'Text');
  await page.getByRole('tab',{name:'Main',exact:true}).click();
  const dock=page.getByRole('toolbar',{name:'Map workspace dock tabs'});
  await expect(dock.getByRole('button')).toHaveCount(2);
  for (const name of ['Surfaces','Timeline']) await expect(dock.getByRole('button',{name,exact:true})).toHaveAttribute('aria-pressed','true');
  await expect(dock.locator('[data-icon-missing]')).toHaveCount(0);
  const surfaces=page.locator('.map-bottom-surfaces'), timeline=page.getByRole('region',{name:'Main timeline',exact:true}), audio=page.getByRole('complementary',{name:'Audio mixer'});
  const boxes=async()=>({s:(await surfaces.boundingBox())!,t:(await timeline.locator('.map-timeline-work-area').boundingBox())!,a:(await audio.boundingBox())!});
  let b=await boxes(); expect(b.s.y+b.s.height).toBeLessThanOrEqual(b.t.y+1); expect(b.s.y+b.s.height).toBeLessThanOrEqual(b.a.y+1); expect(b.t.x+b.t.width).toBeLessThanOrEqual(b.a.x+1);
  await expect(timeline.locator('.map-clip')).toHaveCount(3);
  await dock.getByRole('button',{name:'Surfaces',exact:true}).click(); await expect(surfaces).toHaveCount(0); await expect(timeline).toBeVisible(); await expect(audio).toBeVisible();
  await dock.getByRole('button',{name:'Timeline',exact:true}).click(); await expect(timeline).toHaveCount(0); await expect(audio).toHaveCount(0);
  await expect(page.getByRole('complementary',{name:'Map workspace dock'})).toHaveAttribute('data-open','false');
  // Keyboard navigation does not change which panels are open until activated.
  await dock.getByRole('button',{name:'Surfaces',exact:true}).focus(); await page.keyboard.press('End'); await page.keyboard.press('Enter');
  await expect(timeline).toBeVisible(); await expect(audio).toBeVisible();
  await audio.getByText('Configure audio',{exact:true}).click();
  await expect(audio.getByRole('button',{name:'Start microphone',exact:true})).toBeVisible();
  await expect(audio.getByLabel('Audio input device',{exact:true})).toBeVisible();
  await audio.getByRole('textbox',{name:'A1 lowDb',exact:true}).fill('3.5'); await page.keyboard.press('Tab');
  await expect(audio.getByRole('textbox',{name:'A1 lowDb',exact:true})).toHaveValue('3.5');
  await audio.getByRole('button',{name:'Mute A1 in mixer',exact:true}).click();
  await expect(audio.getByRole('button',{name:'Unmute A1 in mixer',exact:true})).toHaveAttribute('aria-pressed','true');
  await expect(page.locator('.map-save-state')).toHaveText('Saved');
  await dock.getByRole('button',{name:'Timeline',exact:true}).click();
  await expect(audio).toHaveCount(0);
  await page.reload(); await switchWorkspace(page,'Visualization');
  await expect(audio).toHaveCount(0); await expect(timeline).toHaveCount(0); await expect(surfaces).toHaveCount(0);
  await expect(page.getByRole('complementary',{name:'Map workspace dock'})).toHaveAttribute('data-open','false');
  await dock.getByRole('button',{name:'Surfaces',exact:true}).click(); await dock.getByRole('button',{name:'Timeline',exact:true}).click();
  await expect(audio.getByRole('textbox',{name:'A1 lowDb',exact:true})).toHaveValue('3.5');
  await page.getByRole('combobox',{name:'Timeline mode'}).selectOption('advanced');
  await expect(page.getByRole('complementary',{name:'Audio mixer'})).toHaveCount(1);
  await audio.getByRole('button',{name:'Close mixer',exact:true}).click();
  await dock.getByRole('button',{name:'Timeline',exact:true}).click();
  await dock.getByRole('button',{name:'Timeline',exact:true}).click();
  await expect(audio).toHaveCount(0);
  await timeline.getByRole('button',{name:'Equalizer A1',exact:true}).click();
  await expect(audio).toBeVisible(); await expect(page.getByRole('toolbar',{name:'Timeline tools'}).getByRole('button',{name:'Audio mixer',exact:true})).toHaveAttribute('aria-pressed','true');
  const resize=page.getByRole('separator',{name:'Resize bottom dock'}); await resize.focus(); await page.keyboard.press('ArrowUp');
  b=await boxes(); expect(b.s.y+b.s.height).toBeLessThanOrEqual(b.t.y+1); expect(b.t.x+b.t.width).toBeLessThanOrEqual(b.a.x+1);
  await page.screenshot({path:info.outputPath('panels-docked.png'),animations:'disabled'});
  await openAppSettings(page); const settings=page.getByRole('dialog',{name:'Aether Map settings'});
  await settings.getByRole('combobox',{name:'Workspace layout'}).selectOption('floating');
  await settings.getByRole('button',{name:/Close/}).click();
  await expect(audio).toBeVisible(); await expect(timeline).toBeVisible(); await expect(surfaces).toBeVisible();
  await page.screenshot({path:info.outputPath('panels-floating.png'),animations:'disabled'});
  await page.getByRole('button',{name:'Document controls',exact:true}).click();
  await page.getByRole('menuitem',{name:'Export options…',exact:true}).click();
  await expect(page.getByRole('dialog',{name:'Export options',exact:true})).toBeVisible();
});
